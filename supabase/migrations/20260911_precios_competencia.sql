-- ─── 3. v_precios_cambios · todos los cambios de precio (sku, lista, mes) ────
-- Una fila por cada mes en que el precio de (sku, lista) difiere del mes anterior con dato.
-- Con un solo mes de histórico la vista está vacía (el histórico acumula desde 2026-09-11).
create or replace view public.v_precios_cambios
with (security_invoker = true) as
select x.sku, x.lista, x.anio, x.mes,
       x.precio      as precio_nuevo,
       x.precio_prev as precio_anterior,
       x.anio_prev, x.mes_prev,
       case when x.precio_prev = 0 then null
            else round((x.precio - x.precio_prev) / x.precio_prev * 100, 2) end as delta_pct
  from (
    select h.sku, h.lista, h.anio, h.mes, h.precio,
           lag(h.precio) over w as precio_prev,
           lag(h.anio)   over w as anio_prev,
           lag(h.mes)    over w as mes_prev
      from public.precios_historico h
    window w as (partition by h.sku, h.lista order by h.anio, h.mes)
  ) x
 where x.precio_prev is not null and x.precio <> x.precio_prev;
comment on view public.v_precios_cambios is
  'Todos los cambios de precio por sku+lista+mes desde precios_historico (base de la elasticidad por cambio de precio).';
grant select on public.v_precios_cambios to authenticated, service_role;
