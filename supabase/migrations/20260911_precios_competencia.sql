--   3. v_precios_cambios     — TODOS los cambios de precio por sku+lista (mes vs mes anterior con dato) a partir
--                              de precios_historico; complementa a v_precios_cambios_mes (que sólo trae el último).
--                              Es la base de la elasticidad por cambio de precio (cálculo en precios/elasticidad.js).
