-- ─── 1. precios_competencia ──────────────────────────────────────────────────
create table if not exists public.precios_competencia (
  id               bigint generated by default as identity primary key,
  sku              text        not null,
  competidor       text        not null,
  marca            text,
  modelo           text,
  especificaciones text,
  precio           numeric     not null check (precio >= 0),
  moneda           text        not null default 'MXN',
  fuente           text,
  url              text,
  fecha            date        not null default current_date,
  comentario       text,
  creado_por       uuid        default auth.uid(),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
comment on table public.precios_competencia is
  'Precios de la competencia por SKU (competidor · marca/modelo · precio sin IVA · fecha). Captura manual desde el drill de Estrategia de Precios.';
create index if not exists precios_competencia_sku_idx on public.precios_competencia (sku, fecha desc);

